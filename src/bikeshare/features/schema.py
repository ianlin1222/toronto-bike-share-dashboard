def feature_schema_hash() -> str:
    encoded = json.dumps(
        {"version": FEATURE_VERSION, "names": FEATURE_NAMES},
        sort_keys=True,
        separators=(",", ":"),
    ).encode()
    return hashlib.sha256(encoded).hexdigest()
